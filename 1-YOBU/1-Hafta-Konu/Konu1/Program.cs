using System;

namespace ConsoleApp1
{
    internal class Program
    {
        static void Main(string[] args)
        {
            Console.WriteLine("Merhaba");
            System.Console.WriteLine("happy new year");
        }
    }
}

/*
namespace: isim uzayı / paket adı demek
internal: erişim belirteci (access modifier), proje içinden erişilebilir
public, private, protected, internal
static: doğrudan hafızaya alınan, nesne üretmeden çağrılan
void: geriye değer döndürmeyen metot tipi
Main: ana program / başlangıç noktası metodu
*/